import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';

/** Encode exact exported glyph bytes; never generate or rewrite SVG geometry. */
export function iconAssets(packageRoot) {
  const folder=path.resolve(packageRoot,'../../assets/icons/seda');
  const catalog=JSON.parse(fs.readFileSync(path.join(folder,'icons.json'),'utf8'));
  const assets={},icons=[];
  for(const entry of catalog.icons){
    const file=path.resolve(folder,entry.file);
    if(!file.startsWith(folder+path.sep)||entry.name in assets)throw Error('Invalid/duplicate SEDA icon asset');
    const bytes=fs.readFileSync(file),sha256=crypto.createHash('sha256').update(bytes).digest('hex');
    if(!bytes.toString('utf8').includes('<svg')||entry.sha256&&entry.sha256!==sha256)throw Error('SEDA icon bytes changed: '+entry.name);
    assets[entry.name]='data:image/svg+xml;base64,'+bytes.toString('base64');
    icons.push({...entry,sha256});
  }
  const source='// Generated by scripts/icon-assets.mjs from exact original SEDA SVG bytes.\n'+
    'export const sedaIconAssets: Record<'+icons.map(icon=>JSON.stringify(icon.name)).join(' | ')+', string> = '+JSON.stringify(assets,null,2)+';\n';
  return {source,catalog:{...catalog,icons}};
}
export function verifyIconAssets(packageRoot){
  const expected=iconAssets(packageRoot);
  if(fs.readFileSync(path.join(packageRoot,'src/components/Icon/seda-icon-assets.ts'),'utf8')!==expected.source)
    throw Error('SEDA icon module is stale; run node scripts/icon-assets.mjs.');
  return expected.catalog;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
  fs.writeFileSync(path.join(root,'src/components/Icon/seda-icon-assets.ts'),iconAssets(root).source);
  console.log('Generated original SEDA icon module');
}
