import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {createPilotServer} from '../../portal/component-lab/pilots/settings-parametric/server.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const dir=path.resolve(process.env.SEDA_VISUAL_OUTPUT||path.join(root,'docs/library/visual-baselines/files-2026-10-30'));
const receipt=JSON.parse(await fs.readFile(path.join(dir,'capture.json')));
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
assert.equal(sha(await fs.readFile(path.join(dir,'reference.png'))),receipt.reference.sha256);
assert.equal(receipt.captures.length,12);
for(const capture of receipt.captures)assert.equal(sha(await fs.readFile(path.join(dir,capture.screenshot))),capture.screenshotSha256);
const require=createRequire(path.join(root,'portal/component-lab/pilots/settings-parametric/package.json'));
const {chromium}=require('playwright');
const server=await createPilotServer({root:dir,port:0});
const browser=await chromium.launch({headless:true,executablePath:process.env.SEDA_BROWSER_EXECUTABLE});
const page=await browser.newPage({viewport:{width:1480,height:1000}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));
try{
 const base='http://127.0.0.1:'+server.address().port;
 await page.goto(base+'/review.html');
 await page.waitForFunction(()=>document.querySelector('#actual').complete&&document.querySelector('#actual').naturalWidth>0);
 assert.equal(await page.locator('#case option').count(),12);
 assert.deepEqual(await page.locator('#reference').evaluate(n=>[n.naturalWidth,n.naturalHeight]),[1440,1288]);
 await page.locator('#amount').fill('0');assert.equal(await page.locator('#actual').evaluate(n=>n.style.opacity),'0');
 await page.locator('#amount').fill('100');assert.equal(await page.locator('#actual').evaluate(n=>n.style.opacity),'1');
 await page.locator('#mode').selectOption('split');await page.locator('#amount').fill('40');
 assert.equal(await page.locator('#actual').evaluate(n=>n.style.clipPath),'inset(0px 60% 0px 0px)');
 await page.locator('#one').click();assert.equal(await page.locator('#board').evaluate(n=>getComputedStyle(n).transform),'matrix(1, 0, 0, 1, 0, 0)');
 await page.locator('#case').selectOption('dark-1920');
 await page.waitForFunction(()=>document.querySelector('#actual').naturalWidth===1920);
 assert.deepEqual(await page.locator('#actual').evaluate(n=>[n.width,n.height]),[1920,1080]);
 await page.locator('#mode').selectOption('matrix');
 await page.waitForFunction(()=>[...document.querySelectorAll('#matrix img')].every(n=>n.complete&&n.naturalWidth>0));
 assert.equal(await page.locator('#matrix img').count(),12);assert.equal(await page.locator('.defect').count(),7);
 for(const file of ['capture.json','reference-source.json','defects.json','comparison.json'])assert.equal((await page.request.get(base+'/'+file)).status(),200);
 assert.deepEqual(errors,[]);
 await fs.writeFile(path.join(dir,'review-verification.json'),JSON.stringify({verifiedAt:new Date().toISOString(),browser:browser.version(),cases:12,defects:7,checks:['reference and 12 case SHA256 match capture receipt','images loaded at original dimensions','overlay opacity','split clipping','1:1 scale','1920 case dimensions','12-image matrix','receipt links'],errors,visualAcceptance:false},null,2)+'\n');
 console.log('PASS: review artifact interactions and all 13 source/case images; no visual acceptance implied.');
}finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
